using System.Collections.Generic;
using System.Reflection;
using System.Text;
using FishNet;
using FishNet.Broadcast;
using FishNet.Object;
using FishNet.Transporting;
using UnityEngine;

namespace FastAndFractured.Multiplayer
{
    /// <summary>Server → clients: map props that broke on the server.</summary>
    public struct WorldBreakBroadcast : IBroadcast
    {
        public int RegistryCount;   // sanity check: both peers must have found the same props
        public int[] Indices;
        public bool PlayEffects;    // false when restoring a state (host migration)
    }

    /// <summary>
    /// Map props that break with plain local physics or triggers and had no networking: the
    /// tennis nets (FixedJoints with a break force) and the destructible trees. Each peer used
    /// to break its own copy, so a net could be broken on one screen and intact on another.
    ///
    /// Every peer still breaks them locally when hit (no delay for the car that hits them); the
    /// server's break is the one that counts and is sent to everyone, so a prop broken on the
    /// server ends up broken on every screen. The list of broken props also goes into the host
    /// migration snapshot.
    ///
    /// No map edits are needed (the networked maps are generated by a tool): the props are found
    /// at runtime and identified by their scene and hierarchy path, the same on every peer.
    /// Added by NetworkedLevelControllerManager.
    /// </summary>
    public sealed class NetworkedWorldBreakables : MonoBehaviour
    {
        public static NetworkedWorldBreakables Instance { get; private set; }

        private Joint[] _joints = new Joint[0];
        private DestructibleTreeHandle[] _trees = new DestructibleTreeHandle[0];
        private bool[] _broken = new bool[0];
        private bool _collected;
        private readonly List<int> _pending = new List<int>();
        private bool _clientRegistered;
        private readonly List<int> _newlyBroken = new List<int>();

        public int Count => _joints.Length + _trees.Length;

        private void Awake() => Instance = this;

        private void Start()
        {
            // This manager is instantiated at runtime, so look at every loaded scene (the map),
            // not only its own.
            var roots = new List<GameObject>();
            for (int i = 0; i < UnityEngine.SceneManagement.SceneManager.sceneCount; i++)
            {
                var scene = UnityEngine.SceneManagement.SceneManager.GetSceneAt(i);
                if (scene.isLoaded) roots.AddRange(scene.GetRootGameObjects());
            }
            Collect(roots.ToArray(), out _joints, out _trees);
            _broken = new bool[Count];
            _collected = true;
            MpCanary.Mark($"World breakables: {_joints.Length} joint(s), {_trees.Length} tree(s)");
            if (_pending.Count > 0) { ApplyBroken(_pending, false); _pending.Clear(); }
        }

        private void OnEnable()
        {
            var client = InstanceFinder.ClientManager;
            if (client == null) return;
            client.RegisterBroadcast<WorldBreakBroadcast>(OnBreakReceived);
            _clientRegistered = true;
        }

        private void OnDisable()
        {
            if (_clientRegistered && InstanceFinder.ClientManager != null)
                InstanceFinder.ClientManager.UnregisterBroadcast<WorldBreakBroadcast>(OnBreakReceived);
            _clientRegistered = false;
        }

        private void OnDestroy()
        {
            if (Instance == this) Instance = null;
        }

        // ── Server: detect breaks ────────────────────────────────────────────────────────
        private void FixedUpdate()
        {
            if (!_collected || !InstanceFinder.IsServerStarted) return;

            _newlyBroken.Clear();
            for (int i = 0; i < Count; i++)
                if (!_broken[i] && IsBrokenLocally(i)) { _broken[i] = true; _newlyBroken.Add(i); }
            if (_newlyBroken.Count > 0)
                Send(_newlyBroken.ToArray(), playEffects: true);
        }

        private bool IsBrokenLocally(int index)
        {
            if (index < _joints.Length) return _joints[index] == null;   // Unity destroys a joint when it breaks
            return _trees[index - _joints.Length].IsBroken;
        }

        private void Send(int[] indices, bool playEffects)
        {
            InstanceFinder.ServerManager.Broadcast(new WorldBreakBroadcast
            {
                RegistryCount = Count,
                Indices = indices,
                PlayEffects = playEffects,
            });
        }

        /// <summary>Server: the props broken so far (host migration snapshot).</summary>
        public int[] ServerBrokenIndices()
        {
            var list = new List<int>();
            for (int i = 0; i < _broken.Length; i++) if (_broken[i]) list.Add(i);
            return list.ToArray();
        }

        /// <summary>Server, migrated match: break the props that were broken, without effects, everywhere.</summary>
        public void ServerRestore(int[] indices)
        {
            if (indices == null || indices.Length == 0) return;
            ApplyBroken(indices, playEffects: false);
            foreach (int i in indices) if (i >= 0 && i < _broken.Length) _broken[i] = true;
            Send(indices, playEffects: false);
            MpCanary.Mark($"World breakables: {indices.Length} restored after host migration");
        }

        // ── Clients ──────────────────────────────────────────────────────────────────────
        private void OnBreakReceived(WorldBreakBroadcast msg, Channel channel)
        {
            if (InstanceFinder.IsServerStarted) return;   // the host broke them itself
            if (msg.Indices == null) return;
            if (!_collected) { _pending.AddRange(msg.Indices); return; }
            if (msg.RegistryCount != Count)
                MpCanary.Mark($"World breakables: server has {msg.RegistryCount} props, this peer {Count} - skipped");
            else
                ApplyBroken(msg.Indices, msg.PlayEffects);
        }

        private void ApplyBroken(IEnumerable<int> indices, bool playEffects)
        {
            foreach (int index in indices)
            {
                if (index < 0 || index >= Count) continue;
                if (index < _joints.Length)
                {
                    if (_joints[index] != null) Destroy(_joints[index]);
                }
                else
                {
                    _trees[index - _joints.Length].Break(playEffects);
                }
            }
        }

        // ── Discovery ────────────────────────────────────────────────────────────────────
        /// <summary>
        /// The map's breakable props in a stable order (by hierarchy path): joints with a finite
        /// break force or torque, and destructible trees. Anything under a NetworkObject (cars,
        /// abilities) is left out - those have their own networking.
        /// </summary>
        public static void Collect(GameObject[] roots, out Joint[] joints, out DestructibleTreeHandle[] trees)
        {
            var jointList = new List<KeyValuePair<string, Joint>>();
            var treeList = new List<KeyValuePair<string, DestructibleTreeHandle>>();
            foreach (var root in roots)
            {
                foreach (var joint in root.GetComponentsInChildren<Joint>(true))
                {
                    if (float.IsInfinity(joint.breakForce) && float.IsInfinity(joint.breakTorque)) continue;
                    if (joint.GetComponentInParent<NetworkObject>(true) != null) continue;
                    var siblings = joint.GetComponents<Joint>();
                    jointList.Add(new KeyValuePair<string, Joint>(PathKey(joint.transform) + "#" + System.Array.IndexOf(siblings, joint), joint));
                }
                foreach (var behaviour in root.GetComponentsInChildren<MonoBehaviour>(true))
                {
                    if (behaviour == null || !DestructibleTreeHandle.IsTree(behaviour)) continue;
                    if (behaviour.GetComponentInParent<NetworkObject>(true) != null) continue;
                    treeList.Add(new KeyValuePair<string, DestructibleTreeHandle>(PathKey(behaviour.transform), new DestructibleTreeHandle(behaviour)));
                }
            }
            jointList.Sort((a, b) => string.CompareOrdinal(a.Key, b.Key));
            treeList.Sort((a, b) => string.CompareOrdinal(a.Key, b.Key));
            joints = jointList.ConvertAll(kv => kv.Value).ToArray();
            trees = treeList.ConvertAll(kv => kv.Value).ToArray();
        }

        /// <summary>
        /// "Root[0]/Child[2]": names plus the ordinal among same-named siblings. Objects created at
        /// runtime go to the end of their parent, so they never shift an existing prop's key.
        /// </summary>
        public static string PathKey(Transform t)
        {
            var parts = new List<string>();
            for (var current = t; current != null; current = current.parent)
            {
                int ordinal = 0;
                if (current.parent != null)
                {
                    for (int i = 0; i < current.GetSiblingIndex(); i++)
                        if (current.parent.GetChild(i).name == current.name) ordinal++;
                }
                else
                {
                    foreach (var root in current.gameObject.scene.GetRootGameObjects())
                    {
                        if (root.transform == current) break;
                        if (root.name == current.name) ordinal++;
                    }
                }
                parts.Add(current.name + "[" + ordinal + "]");
            }
            parts.Add(t.gameObject.scene.name);
            parts.Reverse();
            var sb = new StringBuilder();
            for (int i = 0; i < parts.Count; i++) { if (i > 0) sb.Append('/'); sb.Append(parts[i]); }
            return sb.ToString();
        }
    }

    /// <summary>
    /// The destructible tree scripts (DestructibleTree, DestructibleOakTree, DestructibleCarobTree
    /// - still work in progress in singleplayer) share one shape: a private _hasSwapped flag,
    /// SwapTree() that hides normalTree and plays the effects. Driven by reflection so they stay
    /// untouched; NetworkedWorldBreakablesTests fails if that shape changes.
    /// </summary>
    public sealed class DestructibleTreeHandle
    {
        private const BindingFlags FLAGS = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public;
        private readonly MonoBehaviour _tree;
        private readonly FieldInfo _hasSwapped, _normalTree;
        private readonly MethodInfo _swap;

        public DestructibleTreeHandle(MonoBehaviour tree)
        {
            _tree = tree;
            var type = tree.GetType();
            _hasSwapped = type.GetField("_hasSwapped", FLAGS);
            _normalTree = type.GetField("normalTree", FLAGS);
            _swap = type.GetMethod("SwapTree", FLAGS, null, System.Type.EmptyTypes, null);
        }

        public static bool IsTree(MonoBehaviour behaviour)
        {
            var type = behaviour.GetType();
            return type.Name.StartsWith("Destructible") && type.Name.EndsWith("Tree")
                && type.GetField("_hasSwapped", FLAGS) != null
                && type.GetField("normalTree", FLAGS) != null
                && type.GetMethod("SwapTree", FLAGS, null, System.Type.EmptyTypes, null) != null;
        }

        public bool IsBroken => _tree != null && (bool)_hasSwapped.GetValue(_tree);

        public void Break(bool playEffects)
        {
            if (_tree == null || IsBroken) return;
            if (playEffects) { _swap.Invoke(_tree, null); return; }
            _hasSwapped.SetValue(_tree, true);
            var normal = _normalTree.GetValue(_tree) as GameObject;
            if (normal != null) normal.SetActive(false);
        }
    }
}

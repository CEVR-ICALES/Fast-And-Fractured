using System;
using System.Collections.Generic;
using UnityEngine;

namespace FastAndFractured.Multiplayer.Lobby
{
    [CreateAssetMenu(menuName = "FastAndFractured/Multiplayer/Map Catalog", fileName = "MapCatalog")]
    public sealed class MapCatalog : ScriptableObject
    {
        [Serializable]
        public struct Entry
        {
            [Tooltip("Stable ID — never reorder or reuse.")]
            public int Id;
            [Tooltip("Key for LocalizedText; falls back to this string if no localization.")]
            public string DisplayNameKey;
            [Tooltip("Singleplayer scene name as it appears in Build Settings. Lives in Assets/FastAndFractured/ — must not be modified for multiplayer.")]
            public string SceneName;
            [Tooltip("Multiplayer scene name as it appears in Build Settings. Generated by the Scene Migration tool into Assets/Multiplayer/Scenes/Networked<Name>.unity. If empty, GetSceneNameForMultiplayer() falls back to SceneName.")]
            public string NetworkedSceneName;
            public Sprite Thumbnail;

            public string GetSceneNameForMultiplayer()
                => string.IsNullOrEmpty(NetworkedSceneName) ? SceneName : NetworkedSceneName;
        }

        [SerializeField] private Entry[] _entries;

        public IReadOnlyList<Entry> Entries => _entries ?? Array.Empty<Entry>();

        /// <summary>The map's name in the current language (DisplayNameKey as is when it is not a key).</summary>
        public static string DisplayName(Entry entry)
        {
            string key = entry.DisplayNameKey;
            if (string.IsNullOrEmpty(key)) return entry.SceneName;
            try
            {
                Assets.SimpleLocalization.Scripts.LocalizationManager.Read();
                if (Assets.SimpleLocalization.Scripts.LocalizationManager.HasKey(key))
                    return Assets.SimpleLocalization.Scripts.LocalizationManager.Localize(key);
            }
            catch (Exception) { }
            return key;
        }

        public bool TryGetById(int id, out Entry entry)
        {
            if (_entries == null) { entry = default; return false; }
            for (int i = 0; i < _entries.Length; i++)
            {
                if (_entries[i].Id == id) { entry = _entries[i]; return true; }
            }
            entry = default;
            return false;
        }
    }
}

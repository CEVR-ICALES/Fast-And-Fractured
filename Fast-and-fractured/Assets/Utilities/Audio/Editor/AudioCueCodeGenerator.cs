using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;

namespace Utilities.Audio.Editor
{
    public static class AudioCueCodeGenerator
    {
        public const string DEFAULT_PATH = "Assets/FastAndFractured/!Common/Managers/Scripts/Generated/GameAudioCues.g.cs";
        private static readonly HashSet<string> _keywords = new HashSet<string>(("abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while").Split(' '));

        public static string SuggestName(string text)
        {
            string result = Regex.Replace(text ?? "", "[^A-Za-z0-9_]", "");
            if (result.Length == 0) result = "Cue";
            if (char.IsDigit(result[0]) || _keywords.Contains(result)) result = "_" + result;
            return result;
        }

        public static bool EnsureNames(AudioCueCatalog catalog)
        {
            var used = new HashSet<string>(StringComparer.Ordinal);
            foreach (var entry in catalog.Entries)
            {
                if (string.IsNullOrEmpty(entry.codeName)) continue;
                if (!IsValid(entry.codeName) || !used.Add(entry.codeName)) throw new InvalidOperationException("Invalid or duplicate audio code name: " + entry.codeName);
            }
            bool changed = false;
            foreach (var entry in catalog.Entries)
            {
                if (!string.IsNullOrEmpty(entry.codeName)) continue;
                string name = SuggestName(string.IsNullOrEmpty(entry.displayName) ? entry.id : entry.displayName);
                string candidate = name;
                for (int suffix = 2; !used.Add(candidate); suffix++) candidate = name + suffix;
                entry.codeName = candidate;
                changed = true;
            }
            return changed;
        }

        public static bool IsValid(string name) => !string.IsNullOrEmpty(name) && Regex.IsMatch(name, "^[A-Za-z_][A-Za-z0-9_]*$") && !_keywords.Contains(name);

        public static string Render(AudioCueCatalog catalog, string className = "GameAudioCues", string namespaceName = "FastAndFractured")
        {
            if (!IsValid(className) || !namespaceName.Split('.').All(IsValid)) throw new InvalidOperationException("Invalid generated audio class or namespace.");
            var used = new HashSet<string>(StringComparer.Ordinal);
            var ids = new HashSet<string>(StringComparer.Ordinal);
            var text = new StringBuilder("// <auto-generated />\nusing Utilities.Audio;\n\nnamespace " + namespaceName + "\n{\n    public static class " + className + "\n    {\n");
            foreach (var entry in catalog.Entries.OrderBy(e => e.codeName, StringComparer.Ordinal))
            {
                if (entry == null || !IsValid(entry.codeName) || !used.Add(entry.codeName) || string.IsNullOrEmpty(entry.id) || !ids.Add(entry.id))
                    throw new InvalidOperationException("Audio keys require unique, valid code names and logical IDs.");
                text.Append("        public static readonly AudioCueId ").Append(entry.codeName).Append(" = new AudioCueId(\"").Append(entry.id.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\");\n");
            }
            return text.Append("    }\n}\n").ToString();
        }

        public static bool Generate(AudioCueCatalog catalog, string path = DEFAULT_PATH)
        {
            if (!path.StartsWith("Assets/", StringComparison.Ordinal) || !path.EndsWith(".g.cs", StringComparison.Ordinal)) throw new InvalidOperationException("Generated audio keys must be an Assets/*.g.cs file.");
            bool namesChanged = EnsureNames(catalog);
            string text = Render(catalog);
            if (namesChanged) { EditorUtility.SetDirty(catalog); AssetDatabase.SaveAssetIfDirty(catalog); }
            if (File.Exists(path) && File.ReadAllText(path) == text) return false;
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, text, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            return true;
        }
    }
}
